#!/usr/bin/env python3
"""Generate the TipTop table/column English naming file (docs/legacy-map/tiptop-naming/<module>.yaml).

Usage: python3 scripts/tiptop/gen_naming.py <naming draft dir> [--module azz]

- Reads the .sch catalog (legacy/catalog/tables.json, produced by sch_catalog.py build) and the
  hand-written naming drafts (one table per line: `xx_file english_table | col1 name1, col2 name2`).
- Shared columns are named by rule (specs/features/azz/legacy_catalog.feature); the drafts can override them:
    xxuser→created_by, xxgrup→created_dept, xxmodu→updated_by, xxdate→updated_on, xxacti→active,
    "No Use"→unused_<code>, language code→lang, customization code→custom_code, industry→industry_code
- Checks: snake_case, at most 63 characters, not a PostgreSQL reserved word, unique table names,
  unique column names within a table, every column covered. Exits with code 1 on any failure.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,62}$")
# PostgreSQL reserved words (common subset that is easy to hit)
RESERVED = {
    "all", "analyse", "analyze", "and", "any", "array", "as", "asc", "both", "case", "cast",
    "check", "collate", "column", "constraint", "create", "current_date", "current_time",
    "current_user", "default", "desc", "distinct", "do", "else", "end", "except", "false",
    "for", "foreign", "from", "grant", "group", "having", "in", "into", "is", "join", "leading",
    "limit", "not", "null", "offset", "on", "only", "or", "order", "primary", "references",
    "select", "session_user", "some", "table", "then", "to", "true", "union", "unique", "user",
    "using", "when", "where", "with", "window",
}
SHARED = {"user": "created_by", "grup": "created_dept", "modu": "updated_by",
          "date": "updated_on", "acti": "active"}
# Uncertain names for the user to confirm (shown highlighted on screen)
VERIFY = {
    "zx_file": ["zx11", "zx15"],
    "gae_file": ["gae07"],
    "gas_file": ["gas02", "gas03", "gas04"],
    "gap_file": ["gap03", "gap06"],
    "gbt_file": ["gbt01"],
    "zt_file": ["zt04"],
    "zta_file": ["zta04"],
    "zoa_file": ["zoa01"],
    "zh_file": ["zh04"],
}


def rule_name(table: str, col: dict) -> str | None:
    name, desc = col["name"], col["description"].strip()
    prefix = table.removesuffix("_file")
    for suffix, target in SHARED.items():
        if name == prefix + suffix:
            return target
    if col["no_use"] or desc.lower().startswith("no use"):
        return f"unused_{name}"
    if desc in ("語言別", "使用語言別"):
        return "lang"
    if desc == "客製碼":
        return "custom_code"
    if desc in ("行業別", "行業別代碼"):
        return "industry_code"
    return None


def parse_drafts(folder: Path) -> dict[str, tuple[str, dict[str, str]]]:
    out: dict[str, tuple[str, dict[str, str]]] = {}
    for f in sorted(folder.glob("*.txt")):
        for line in f.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            head, _, body = line.partition("|")
            table, english = head.split()
            cols = dict(p.split() for p in body.split(",") if p.strip())
            prev = out.get(table, (english, {}))[1]
            out[table] = (english, {**prev, **cols})
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("drafts", type=Path)
    ap.add_argument("--module", default="azz")
    args = ap.parse_args()

    catalog = json.loads((ROOT / "legacy/catalog/tables.json").read_text(encoding="utf-8"))
    drafts = parse_drafts(args.drafts)
    errors: list[str] = []
    lines = [
        f"# TipTop table/column English naming ({args.module}). Rules: specs/features/azz/legacy_catalog.feature",
        "# Generated by scripts/tiptop/gen_naming.py; change names here and re-import (make legacy-catalog).",
        "# Format: legacy table: { name: English table name, columns: { legacy column: English name }, verify: [names to confirm] }",
        "",
    ]
    seen_tables: dict[str, str] = {}
    for table in sorted(t for t, v in catalog.items() if v["module"] == args.module):
        meta = catalog[table]
        if table not in drafts:
            errors.append(f"{table}: no English name")
            continue
        english, explicit = drafts[table]
        if not NAME_RE.match(english) or english in RESERVED:
            errors.append(f"{table}: invalid table name {english}")
        if english in seen_tables:
            errors.append(f"{table}: table name {english} duplicates {seen_tables[english]}")
        seen_tables[english] = table
        lines.append(f"{table}:  # {meta['title']}")
        lines.append(f"  name: {english}")
        lines.append("  columns:")
        used: dict[str, str] = {}
        for col in meta["columns"]:
            name = explicit.get(col["name"]) or rule_name(table, col)
            if not name:
                errors.append(f"{table}.{col['name']}: no English name ({col['description']})")
                continue
            if not NAME_RE.match(name) or name in RESERVED:
                errors.append(f"{table}.{col['name']}: invalid column name {name}")
            if name in used:
                errors.append(f"{table}.{col['name']}: column name {name} duplicates {used[name]}")
            used[name] = col["name"]
            lines.append(f"    {col['name']}: {name}  # {col['description']}")
        unknown = set(explicit) - {c["name"] for c in meta["columns"]}
        if unknown:
            errors.append(f"{table}: draft has columns the catalog lacks {sorted(unknown)}")
        if table in VERIFY:
            lines.append(f"  verify: [{', '.join(VERIFY[table])}]")
        lines.append("")
    extra = set(drafts) - set(catalog)
    if extra:
        errors.append(f"draft has tables the catalog lacks {sorted(extra)}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    out = ROOT / f"docs/legacy-map/tiptop-naming/{args.module}.yaml"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(seen_tables)} tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
